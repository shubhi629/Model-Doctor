"""Run ModelDoctor on every sample dataset (and with each algorithm forced as Model 1)
and write the honest test-split results to RESULTS.md at the repository root.

    cd backend
    python scripts/run_experiments.py            # full models (a few minutes)
    python scripts/run_experiments.py --fast     # smaller ensembles
"""

import argparse
import sys
import time
import warnings
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BASE_DIR))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from ml.data.loader import load_dataset  # noqa: E402
from ml.pipeline import TrainingConfig, train_modeldoctor  # noqa: E402

DATA = BASE_DIR.parent / "sample_data"
DATASETS = [
    ("loans.csv", "default", "Synthetic loan default (binary, 5,000 rows)"),
    ("customer_tiers.csv", "tier", "Synthetic customer tiers (multiclass, 3,000 rows, noisy sub-population)"),
    ("breast_cancer.csv", "diagnosis", "Wisconsin breast cancer, real (binary, 569 rows)"),
]
MODELS = ["Logistic Regression", "Decision Tree", "Random Forest", "XGBoost", "KNN"]


def row(name, rep):
    cmp = {c["method"]: c for c in rep["comparison"]}
    md, base = cmp["ModelDoctor"], cmp["Confidence baseline"]
    f = lambda v: "—" if v is None else f"{v:.3f}"  # noqa: E731
    return (
        f"| {name} | {rep['selected_model']} | {rep['reliability_mode']} | {rep['overall_error_rate']:.1%} | "
        f"{md['coverage']:.1%} | {base['selective_risk']:.1%} | {md['selective_risk']:.1%} | "
        f"{f(rep['auroc']['confidence_baseline'])} | {f(rep['auroc']['modeldoctor'])} | "
        f"{rep['calibration']['modeldoctor']['ece']:.3f} |"
    )


HEADER = (
    "| Run | Model 1 | Reliability mode | Error (no filter) | Coverage | Baseline error @ same cov. | "
    "ModelDoctor error | AUROC baseline | AUROC ModelDoctor | ECE ModelDoctor |\n"
    "|---|---|---|---|---|---|---|---|---|---|"
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--skip-per-model", action="store_true")
    args = ap.parse_args()
    warnings.filterwarnings("ignore")

    lines = [
        "# ModelDoctor experiment results",
        "",
        f"Generated by `backend/scripts/run_experiments.py`{' --fast' if args.fast else ''}. All numbers are on the "
        "held-out **test split** (20%), which is never used for training or tuning. The confidence baseline is "
        "evaluated at exactly the same coverage as ModelDoctor's TRUST decisions. Target risk 5%, minimum coverage 30%.",
        "",
        "## Automatic model selection",
        "",
        HEADER,
    ]
    verdicts = []
    t_all = time.time()
    for fname, target, desc in DATASETS:
        df = load_dataset(str(DATA / fname), target)
        t0 = time.time()
        _, rep = train_modeldoctor(df, target, TrainingConfig(fast=args.fast))
        print(f"{fname}: {rep['selected_model']} {rep['reliability_mode']} ({time.time() - t0:.0f}s) {rep['verdict']}")
        lines.append(row(desc, rep))
        verdicts.append(f"- **{desc}:** {rep['verdict']}")

    lines += ["", "Verdicts:", ""] + verdicts

    if not args.skip_per_model:
        for fname, target, desc in DATASETS[:2]:
            lines += ["", f"## Each algorithm forced as Model 1 — {desc}", "", HEADER]
            df = load_dataset(str(DATA / fname), target)
            for m in MODELS:
                _, rep = train_modeldoctor(df, target, TrainingConfig(fast=args.fast, force_model=m))
                print(f"  {fname} / {m}: {rep['verdict']}")
                lines.append(row(m, rep))

    lines += [
        "",
        "## Reading these results",
        "",
        "- *Reliability mode* `confidence_fallback` means the calibration split had fewer than 30 wrong (or right) "
        "predictions, so Model 2 could not be trained and ModelDoctor falls back to Model 1's calibrated confidence "
        "(identical to the baseline by construction).",
        "- Model 1 is calibrated inside the train split, so on clean i.i.d. data its confidence is already a strong "
        "error detector and ModelDoctor often only matches it. Gains are expected where Model 1 is poorly "
        "calibrated (e.g. Decision Tree, KNN) or where input-quality signals carry extra information.",
        "",
        f"Total runtime: {time.time() - t_all:.0f}s.",
    ]
    out = BASE_DIR.parent / "RESULTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("Wrote", out)


if __name__ == "__main__":
    main()
